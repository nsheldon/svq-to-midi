"""Generate SVQKit/Sources/SVQKit/FantomSPatchNames.swift from fantoms_lists.json (see parse_fs_lists.py).

The names in fantoms_lists.json already carry the Fantom-S 1.09 program's own spelling and spacing
(check_firmware_names.py), e.g. PR-E 054 "FS AlphaRave" and PR-E 099 "OutOf  sortz".

    python3 -I parse_fs_lists.py dl/FANTOM-S_PA.txt fantoms_lists.json && python3 -I gen_fantom_s.py
"""
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'fantoms_lists.json')))
groups = ['PR-A', 'PR-B', 'PR-C', 'PR-D', 'PR-E', 'PR-F']
presets = d['presets']
assert list(presets) == groups, list(presets)
assert all(len(presets[g]) == 128 for g in groups[:5]) and len(presets['PR-F']) == 8
assert len(d['gm2']) == 256 and len({(l, p) for l, p, _ in d['gm2']}) == 256
assert len(d['presetRhythmSets']) == 32
# GM2 rhythm sets are on the GM2 standard's programs.
kit_programs = [0, 8, 16, 24, 25, 32, 40, 48, 56]
assert len(d['gm2RhythmSets']) == len(kit_programs)


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def wrap(items, indent='            ', width=110):
    out, line = [], indent
    for item in items:
        piece = item + ', '
        if len(line) + len(piece) > width:
            out.append(line.rstrip()); line = indent
        line += piece
    if line.strip():
        out.append(line.rstrip())
    return '\n'.join(out)


src = ['''// Generated by Reference Material/Fantom-S Lists/gen_fantom_s.py from the Fantom-S/S88 Sound
// List, with the spelling the Fantom-S 1.09 program stores; do not edit by hand.

/// Factory sound names of the Fantom-S and Fantom-S88. Their songs are saved in the same format as
/// the Fantom-X's, but the preset groups are fewer and some names differ.
enum FantomSPatchNames {
    /// Preset Patches PR-A to PR-E (Bank Select MSB 87, LSB 64-68), 128 each, and PR-F (LSB 69,
    /// Fantom-S88 only), 8 Patches.
    static let presets: [[String]] = [''']
for g in groups:
    src.append(f'        // {g}')
    src.append('        [')
    src.append(wrap([q(n) for n in presets[g]]))
    src.append('        ],')
src.append('''    ]

    /// Preset Rhythm Sets (MSB 86, LSB 64), PRST 001-032.
    static let presetRhythmSets: [String] = [''')
src.append(wrap([q(n) for n in d['presetRhythmSets']], indent='        '))
src.append('''    ]

    /// GM2 Patches (MSB 121) in the Sound List's order: Bank Select LSB, 0-based program, name.
    static let gm2: [(lsb: Int, program: Int, name: String)] = [''')
src.append(wrap([f'({l}, {p}, {q(n)})' for l, p, n in d['gm2']], indent='        '))
src.append('''    ]

    /// GM2 Rhythm Sets (MSB 120): 0-based program, name.
    static let gm2RhythmSets: [(program: Int, name: String)] = [''')
src.append(wrap([f'({p}, {q(n)})' for p, n in zip(kit_programs, d['gm2RhythmSets'])], indent='        '))
src.append('''    ]
}
''')
out = os.path.join(here, '../../SVQKit/Sources/SVQKit/FantomSPatchNames.swift')
open(out, 'w').write('\n'.join(src))
print('wrote FantomSPatchNames.swift')
