"""Generate SVQKit/Sources/SVQKit/FA76Names.swift from fantom_lists.json (see parse_fantom.py).

Three names are printed with one space where the Fantom's own data has two (pdftotext -layout
can't tell); the firmware's spacing is used (the Fantom 1.20 system update stores every preset
Patch with its name: 637 of the 640 names match it as printed, these three with two spaces).

    python3 parse_fantom.py && python3 gen_fantom.py
"""
import json

d = json.load(open('fantom_lists.json'))
FIXES = {('PR-B', 72): ('101 Bass', '101  Bass'), ('PR-B', 101): ('Dolce p/m/f', 'Dolce  p/m/f'),
         ('PR-D', 51): ('Quasar /Aft', 'Quasar  /Aft')}
groups = ['PR-A', 'PR-B', 'PR-C', 'PR-D', 'PR-E']
presets = d['presets']
for (group, number), (printed, fixed) in FIXES.items():
    g = groups.index(group)
    assert presets[g][number - 1] == printed, (group, number, presets[g][number - 1])
    presets[g][number - 1] = fixed
# GM2 rhythm sets are on the GM2 standard's programs.
kit_programs = [0, 8, 16, 24, 25, 32, 40, 48, 56]
assert len(d['gm2RhythmSets']) == len(kit_programs)


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def wrap(items, indent='            ', width=110):
    out, line = [], indent
    for item in items:
        piece = item + ', '
        if len(line) + len(piece) > width:
            out.append(line.rstrip()); line = indent
        line += piece
    if line.strip():
        out.append(line.rstrip())
    return '\n'.join(out)


src = ['''// Generated by Reference Material/Fantom Lists/gen_fantom.py from the Patch List and Rhythm Set
// List in the Fantom (FA-76) MIDI Implementation; do not edit by hand.

/// Factory sound names of the original Fantom (FA-76), for songs saved in "SV02" files.
enum FA76Names {
    /// Preset Patches PR-A to PR-E (Bank Select MSB 87, LSB 71-75), 128 each.
    static let presets: [[String]] = [''']
for g, names in zip(groups, presets):
    src.append(f'        // {g}')
    src.append('        [')
    src.append(wrap([q(n) for n in names]))
    src.append('        ],')
src.append('''    ]

    /// Preset Rhythm Sets (MSB 86, LSB 71), PRST 001-016.
    static let presetRhythmSets: [String] = [''')
src.append(wrap([q(n) for n in d['presetRhythmSets']], indent='        '))
src.append('''    ]

    /// GM2 Patches (MSB 121) in the Patch List's order: Bank Select LSB, 0-based program, name.
    static let gm2: [(lsb: Int, program: Int, name: String)] = [''')
src.append(wrap([f'({l}, {p}, {q(n)})' for l, p, n in d['gm2']], indent='        '))
src.append('''    ]

    /// GM2 Rhythm Sets (MSB 120): 0-based program, name.
    static let gm2RhythmSets: [(program: Int, name: String)] = [''')
src.append(wrap([f'({p}, {q(n)})' for p, n in zip(kit_programs, d['gm2RhythmSets'])], indent='        '))
src.append('''    ]
}
''')
open('../../SVQKit/Sources/SVQKit/FA76Names.swift', 'w').write('\n'.join(src))
print('wrote FA76Names.swift')
