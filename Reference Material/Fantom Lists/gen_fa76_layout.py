"""Generate SVQKit/Sources/SVQKit/FA76Layout.swift from fa76_map.json (see parse_fa76_map.py).

The Fantom's Performance and Multitimbre records hold the map's sections, each starting on a byte
boundary, in this order: Common, MFX 1-3, Chorus, Reverb, MIDI x16, Part x16 (each Part after 2
undocumented bits), and for a Performance also Zone x16 and Controller. Parameters use the map's
bit widths, most-significant-bit first; 64-centered parameters with narrower masks are stored
re-centered (as on the Fantom-S/X). This accounts for exactly 1126 (Performance) and 954
(Multitimbre) bytes. The Multitimbre's sections are the Performance's (its Common, MFX and Chorus
tables are identical; its Reverb, MIDI and Part pages don't parse cleanly but match where they do).

    python3 parse_fa76_map.py && python3 gen_fa76_layout.py
"""
import json, re

M = json.load(open('fa76_map.json'))


def params(sec):
    return [p for p in M[sec] if 'off' in p]


def width(p):
    return sum(c.count('a') + c.count('b') + c.count('c') + c.count('d') for c in p['masks'])


def rng(p):
    m = re.search(r'\((\d+)\s*[—–-]\s*(\d+)\)', p['name'])
    return (int(m.group(1)), int(m.group(2))) if m else None


def centered(p):
    w, r = width(p), rng(p)
    return bool(r and w < 7 and r[1] >= (1 << w) and r[0] <= 64 <= r[1])


SECTIONS = [('common', 'Performance Common', 0x35), ('mfx', 'Performance Common MFX', 0x111),
            ('chorus', 'Performance Common Chorus', 0x34), ('reverb', 'Performance Common Reverb', 0x53),
            ('midi', 'Performance MIDI', 0x0C), ('part', 'Performance Part', 0x31),
            ('zone', 'Performance Zone', 0x14), ('controller', 'Performance Controller', 0x33)]
for name, sec, total in SECTIONS:
    sysex = sum(len(p['masks']) for p in params(sec))
    assert sysex == (total >> 8) * 128 + (total & 0xFF), (sec, sysex, total)
for a, b in [('Performance Common', 'Multitimbre Common'), ('Performance Common MFX', 'Multitimbre Common MFX'),
             ('Performance Common Chorus', 'Multitimbre Common Chorus')]:
    assert [(p['off'], p['masks']) for p in params(a)] == [(p['off'], p['masks']) for p in params(b)], b
decay = [i for i, p in enumerate(params('Performance Part')) if p['off'] == 0x21]
assert len(decay) == 1


def table(name, sec):
    ps = params(sec)
    out = [f'    /// {sec} ({len(ps)} parameters, {sum(len(p["masks"]) for p in ps)} SysEx bytes, {sum(width(p) for p in ps)} bits)',
           f'    static let {name}: [FantomParameter] = [']
    line = '       '
    for p in ps:
        item = f' F({len(p["masks"])}, {width(p)}{", c" if centered(p) else ""}),'
        if len(line) + len(item) > 104:
            out.append(line); line = '       '
        line += item
    out.append(line)
    out.append('    ]')
    return '\n'.join(out)


body = '\n\n'.join(table(n, s) for n, s, _ in SECTIONS)
# The Setup section's heading shares a line with another table, so parse_fa76_map.py doesn't find it;
# it is short, so it is written out from the map: Sound Mode (0000 0aaa), Multitimbre, Performance
# and Patch Bank Select MSB/LSB and program (0aaa aaaa each), MFX/Chorus/Reverb switches
# (0000 000a), Transpose (0000 aaaa, 59-70: -5..+6) and Octave Shift (0000 0aaa, 61-67: -3..+3).
# Total Size 0F = 15 bytes, 76 bits.
setup = [(1, 3)] + [(1, 7)] * 9 + [(1, 1)] * 3 + [(1, 4, True), (1, 3, True)]
assert len(setup) == 15 and sum(p[1] for p in setup) == 76
body += '''

    /// Setup (01 00 00 00): Sound Mode, the selected Multitimbre, Performance and Patch, effect
    /// switches, transpose and octave shift (15 parameters, 15 SysEx bytes, 76 bits)
    static let setup: [FantomParameter] = [
        ''' + ', '.join(f'F({p[0]}, {p[1]}{", c" if len(p) > 2 else ""})' for p in setup) + ''',
    ]'''
swift = f'''// Generated by Reference Material/Fantom Lists/gen_fa76_layout.py from the "Parameter Address Map"
// in the Fantom (FA-76) MIDI Implementation; do not edit by hand. Same conventions as FantomPatchLayout.
// The Multitimbre uses the Performance's Common, MFX, Chorus, Reverb, MIDI and Part tables.

private let c = true
private func F(_ sysExBytes: Int, _ bits: Int, _ centered: Bool = false) -> FantomParameter {{
    FantomParameter(sysExBytes: sysExBytes, bits: bits, centered: centered)
}}

enum FA76Layout {{
{body}

    /// Index in `part` of Decay Time Offset (00 21). Its slot in the saved Part holds an undocumented
    /// value instead (126 in 940 of the firmware's 1024 preset Parts, 2 in the rest), so 64 is sent.
    static let partDecayTimeOffsetIndex = {decay[0]}
}}
'''
open('../../SVQKit/Sources/SVQKit/FA76Layout.swift', 'w').write(swift)
print('wrote FA76Layout.swift')
