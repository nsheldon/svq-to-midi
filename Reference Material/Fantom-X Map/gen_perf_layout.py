"""Generate SVQKit/Sources/SVQKit/FantomPerformanceLayout.swift from map678.json.

map678.json is the Fantom-X Owner's Manual's Parameter Address Map (MIDI Implementation),
parsed by parse_map.py from `pdftotext -layout` output of the manual's MIDI Implementation pages.
Each parameter gives its SysEx byte count (one nibble per byte for multi-byte values), its stored
bit width (the bits in its mask) and whether it is a 64-centered value stored re-centered in fewer
bits (the same rules as FantomPatchLayout, which was verified against Patch dumps).

Run from this folder:  python3 gen_perf_layout.py
"""
import json, re

MAP = json.load(open('map678.json'))


def width(p):
    return sum(c.count('a') + c.count('b') + c.count('c') + c.count('d') for c in p['masks'])


def rng(p):
    m = re.search(r'\((-?\d+)\s*-\s*(-?\d+)\)\s*$', p['name'])
    return (int(m.group(1)), int(m.group(2))) if m else None


def centered(p):
    w, r = width(p), rng(p)
    return bool(r and w < 7 and r[1] >= (1 << w) and r[0] <= 64 <= r[1])


def params(section):
    return [p for p in MAP[section] if 'off' in p]


def table(name, section, doc):
    ps = params(section)
    out = [f'    /// {doc} ({len(ps)} parameters, {sum(len(p["masks"]) for p in ps)} SysEx bytes, {sum(width(p) for p in ps)} bits)',
           f'    static let {name}: [FantomParameter] = [']
    line = '       '
    for p in ps:
        item = f' F({len(p["masks"])}, {width(p)}{", c" if centered(p) else ""}),'
        if len(line) + len(item) > 104:
            out.append(line)
            line = '       '
        line += item
    out.append(line)
    out.append('    ]')
    return '\n'.join(out)


# The Performance's effect sections must match the Patch's (FantomPatchLayout.mfx/chorus/reverb).
for a, b in [('Performance Common MFX', 'Patch Common MFX'), ('Performance Common Chorus', 'Patch Common Chorus'),
             ('Performance Common Reverb', 'Patch Common Reverb')]:
    assert [(len(p['masks']), width(p), centered(p)) for p in params(a)] == \
           [(len(p['masks']), width(p), centered(p)) for p in params(b)], a

decay = [i for i, p in enumerate(params('Performance Part')) if p['off'] == 0x21]
assert len(decay) == 1

body = '\n\n'.join([
    table('common', 'Performance Common', 'Performance Common'),
    table('midi', 'Performance MIDI', 'Performance MIDI, one per Part'),
    table('part', 'Performance Part', 'Performance Part'),
    table('zone', 'Performance Zone', 'Performance Zone, one per Part'),
    table('controller', 'Performance Controller', 'Performance Controller'),
])
swift = f'''// Generated by Reference Material/Fantom-X Map/gen_perf_layout.py from the "Parameter Address Map"
// in the Fantom-X Owner's Manual (MIDI Implementation); do not edit by hand. Same conventions as
// FantomPatchLayout. The Performance's MFX, Chorus and Reverb sections are identical to the Patch's.

private let c = true
private func F(_ sysExBytes: Int, _ bits: Int, _ centered: Bool = false) -> FantomParameter {{
    FantomParameter(sysExBytes: sysExBytes, bits: bits, centered: centered)
}}

enum FantomPerformanceLayout {{
{body}

    /// Index in `part` of Decay Time Offset (00 21), which is stored at the end of the Part.
    static let partDecayTimeOffsetIndex = {decay[0]}
}}
'''
open('../../SVQKit/Sources/SVQKit/FantomPerformanceLayout.swift', 'w').write(swift)
print('wrote FantomPerformanceLayout.swift')
