"""Generate SVQKit/Sources/SVQKit/SRXBoards.swift.

- SRX-01 to SRX-12 and SRX-98: srx_lists.json (the owner's manuals, see parse_srx.py), with the exact
  spacing of Roland Japan's text lists (jp_lists.json, see parse_jp.py) where a name matches apart
  from spacing.
- SRX-99: special_lists.json (Roland Japan's text list).
- SRX-97: Bank Select only, from Roland's SN 132 v3.00 (2007): 12 patches at LSB 97; no list found.
- SRX-96: no list or Bank Select found; title only.

Run from this directory:  python3 parse_srx.py && python3 parse_jp.py && python3 gen_srx.py
"""
import json, os

TITLES = {
    1: 'Dynamic Drum Kits', 2: 'Concert Piano', 3: 'Studio SRX', 4: 'Symphonique Strings',
    5: 'Supreme Dance', 6: 'Complete Orchestra', 7: 'Ultimate Keys', 8: 'Platinum Trax',
    9: 'World Collection', 10: 'Big Brass Ensemble', 11: 'Complete Piano', 12: 'Classic EPs',
    96: 'World Collection & Legendary XP Essentials', 97: 'Rock Organ', 98: 'Analog Essentials',
    99: 'Special Wave Expansion',
}

# Corrections to the manuals' text.
FIXES = {
    (7, 239): ('TB3O3 Reso', 'TB303 Reso'),  # printed with a letter O
    (7, 316): ('H2O', 'H 2 O'),  # three words on the page (pdftotext -raw), as in Roland Japan's list
}

boards = {}
for key, v in json.load(open('srx_lists.json')).items():
    board = int(key)
    v['source'] = f'Roland SRX-{board:02d} Owner’s Manual, patch list for the Fantom series'
    boards[board] = v
jp = json.load(open('jp_lists.json'))
for key, lists in jp.items():
    for kind in ('patches', 'rhythmSets'):
        names = boards[int(key)][kind]
        for i, (ours, theirs) in enumerate(zip(names, lists[kind])):
            theirs = theirs.replace('\u2019', "'")
            if ours != theirs and ours.split() == theirs.split() and len(theirs) <= 12:
                names[i] = theirs
boards[97] = {'patches': [''] * 12, 'rhythmSets': [], 'patchLSBs': [97], 'rhythmLSB': None,
              'source': 'Roland SN 132 v3.00 (2007): Bank Select only; no patch list found'}
if os.path.exists('special_lists.json'):
    for key, v in json.load(open('special_lists.json')).items():
        boards[int(key)] = v

for (board, number), (printed, fixed) in FIXES.items():
    assert boards[board]['patches'][number - 1] == printed, (board, number)
    boards[board]['patches'][number - 1] = fixed


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def names(items, indent='            '):
    lines, line = [], indent
    for item in items:
        piece = q(item) + ', '
        if len(line) + len(piece) > 110:
            lines.append(line.rstrip())
            line = indent
        line += piece
    if line.strip():
        lines.append(line.rstrip())
    return '\n'.join(lines)


out = ['''// Generated by Reference Material/SRX Lists/gen_srx.py; do not edit by hand.
//
// Patch and Rhythm Set names of the Roland SRX Wave Expansion boards, used to name the SRX
// sounds of Fantom-X songs. SRX sounds are selected with Bank Select MSB 93 (patches) or 92
// (rhythm sets) and an LSB assigned to each board, wherever the board is installed.

public enum SRXBoards {
    struct Board: Sendable {
        let title: String
        /// Bank Select LSBs of the patches, one per 128 patches.
        let patchLSBs: [Int]
        /// Bank Select LSB of the rhythm sets (nil if the board has none).
        let rhythmLSB: Int?
        /// Patch names in order (patch 1 first); empty where the name isn't known.
        let patches: [String]
        /// Rhythm Set names in order.
        let rhythmSets: [String]
    }

    /// Every SRX board by number, with its title (names known or not).
    public static let titles: [Int: String] = [''']
for b in sorted(TITLES):
    out.append(f'        {b}: {q(TITLES[b])},')
out.append('''    ]

    static let boards: [Int: Board] = [''')
for b in sorted(boards):
    v = boards[b]
    rhythm = 'nil' if v.get('rhythmLSB') is None else str(v['rhythmLSB'])
    out.append(f'        {b}: Board(')
    out.append(f'            title: {q(TITLES[b])},')
    out.append(f'            // {v["source"]}')
    out.append(f'            patchLSBs: {v["patchLSBs"]}, rhythmLSB: {rhythm},')
    out.append('            patches: [')
    out.append(names(v['patches']))
    out.append('            ],')
    if v['rhythmSets']:
        out.append('            rhythmSets: [')
        out.append(names(v['rhythmSets']))
        out.append('            ]),')
    else:
        out.append('            rhythmSets: []),')
out.append('''    ]

    /// The board, 1-based number on the board and name of an SRX patch selected by Bank Select
    /// LSB and 0-based Program Change. Nil if the LSB belongs to no known board.
    public static func patch(lsb: Int, program: Int) -> (board: Int, number: Int, name: String?)? {
        for (number, board) in boards {
            if let bank = board.patchLSBs.firstIndex(of: lsb) {
                let index = bank * 128 + program
                let name = board.patches.indices.contains(index) ? board.patches[index] : ""
                return (number, index + 1, name.isEmpty ? nil : name)
            }
        }
        return nil
    }

    /// The board, 1-based number and name of an SRX rhythm set selected by Bank Select LSB and program.
    public static func rhythmSet(lsb: Int, program: Int) -> (board: Int, number: Int, name: String?)? {
        for (number, board) in boards where board.rhythmLSB == lsb {
            return (number, program + 1, board.rhythmSets.indices.contains(program) ? board.rhythmSets[program] : nil)
        }
        return nil
    }
}
''')
path = '../../SVQKit/Sources/SVQKit/SRXBoards.swift'
open(path, 'w').write('\n'.join(out))
print('wrote', path, {b: (len(v['patches']), len(v['rhythmSets'])) for b, v in sorted(boards.items())})
